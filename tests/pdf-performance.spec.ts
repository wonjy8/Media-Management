import {test,expect} from '@playwright/test'
import {execFileSync} from 'node:child_process'
test.use({launchOptions:{executablePath:'/usr/bin/chromium',args:['--no-sandbox']}})
test('PDF 생성 중에도 화면이 응답하고 빠른 편집 뒤에는 마지막 내용만 표시',async({page})=>{
 test.setTimeout(90000)
 await page.addInitScript(()=>{
  const state={maxTask:0,tasks:0};Object.assign(window,{pdfPerformance:state})
  new PerformanceObserver(list=>{for(const entry of list.getEntries()){state.maxTask=Math.max(state.maxTask,entry.duration);state.tasks++}}).observe({type:'longtask',buffered:true})
 })
 await page.goto('http://localhost:4174/Media-Management/admin/pdf/?demo=1')
 const preview=page.getByRole('region',{name:'신청서 PDF 미리보기'})
 await expect(preview.getByRole('img')).toHaveCount(2,{timeout:40000})
 await expect(preview.getByRole('status')).toHaveCount(0,{timeout:40000})
 const initial=await page.evaluate(()=>Reflect.get(window,'pdfPerformance'))
 console.log('Initial PDF main-thread metrics:',initial)
 expect(initial.maxTask).toBeLessThan(500)
 await page.evaluate(()=>{const state=Reflect.get(window,'pdfPerformance');state.maxTask=0;state.tasks=0})
 const oldPixels=await preview.locator('canvas').last().evaluate(c=>(c as HTMLCanvasElement).toDataURL())
 await page.getByLabel('이름',{exact:true}).fill('처음입력')
 await page.getByLabel('이름',{exact:true}).fill('마지막입력')
 await page.getByLabel('문서 제목',{exact:true}).fill('최종 문서 제목')
 await expect(preview.getByRole('status')).toHaveCount(0,{timeout:40000})
 await expect.poll(async()=>preview.locator('canvas').last().evaluate(c=>(c as HTMLCanvasElement).toDataURL()),{timeout:40000}).not.toBe(oldPixels)
 await expect(preview.getByRole('status')).toHaveCount(0,{timeout:40000})
 const editing=await page.evaluate(()=>Reflect.get(window,'pdfPerformance'))
 console.log('Editing PDF main-thread metrics:',editing)
 expect(editing.maxTask).toBeLessThan(500)
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'샘플 PDF 저장',exact:true}).click()
 await (await download).saveAs('/tmp/media-performance-final.pdf')
 const text=execFileSync('pdftotext',['-layout','/tmp/media-performance-final.pdf','-'],{encoding:'utf8'})
 expect(text).toContain('마지막입력');expect(text).toContain('최종 문서 제목');expect(text).not.toContain('처음입력')
})
