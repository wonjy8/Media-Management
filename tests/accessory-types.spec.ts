import {test,expect} from '@playwright/test'
test.use({launchOptions:{executablePath:'/usr/bin/chromium',args:['--no-sandbox']}})
const fixture=[{id:'camera-a',code:'A',name:'카메라A',model:'SONY',group:'영상',qty:2,image:''},{id:'camera-b',code:'B',name:'카메라B',model:'SONY',group:'영상',qty:2,image:''}]
test('부속품 등록 시 여러 일반 장비 선택, 중첩 선택 차단, 목록 숨김과 공유 선택',async({page})=>{
 await page.addInitScript(items=>{if(!localStorage.getItem('media-equipment'))localStorage.setItem('media-equipment',JSON.stringify(items))},fixture)
 await page.goto('http://localhost:5173/admin/equipment/?demo=1')
 await page.getByRole('button',{name:'장비 등록',exact:true}).click()
 await page.getByLabel('장비명',{exact:true}).fill('공용 배터리')
 await page.getByLabel('총 수량',{exact:true}).fill('2')
 await page.getByRole('checkbox',{name:'부속품',exact:true}).check()
 await expect(page.getByLabel('연결할 장비',{exact:true})).toHaveCount(0)
 await page.locator('.dialog').getByRole('button',{name:'저장',exact:true}).click()
 await expect(page.locator('.dialog').getByRole('alert')).toContainText('하나 이상')
 await page.getByLabel('종속될 장비 선택',{exact:true}).selectOption('camera-a')
 await page.getByLabel('종속될 장비 선택',{exact:true}).selectOption('camera-b')
 await expect(page.getByRole('button',{name:'카메라A 연결 해제',exact:true})).toHaveText('연결 해제')
 await page.locator('.dialog').getByRole('button',{name:'저장',exact:true}).click()
 await page.reload();await page.getByRole('button',{name:'공용 배터리 수정',exact:true}).click()
 await expect(page.getByRole('checkbox',{name:'부속품',exact:true})).toBeChecked()
 await expect(page.locator('.accessory-editor-row')).toHaveCount(2)
 await expect(page.getByLabel('연결할 장비',{exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'장비 편집 닫기'}).click()
 await page.getByRole('button',{name:'장비 등록',exact:true}).click();await page.getByRole('checkbox',{name:'부속품',exact:true}).check()
 await expect(page.getByLabel('종속될 장비 선택').locator('option').filter({hasText:'공용 배터리'})).toHaveCount(0)
 await page.getByRole('button',{name:'장비 편집 닫기'}).click()
 await page.goto('http://localhost:5173/equipment/?demo=1')
 await expect(page.locator('.card')).toHaveCount(2)
 await expect(page.getByRole('button',{name:'공용 배터리 담기'})).toHaveCount(0)
 await page.getByRole('button',{name:'카메라A 담기'}).click()
 await expect(page.getByRole('dialog')).toContainText('공용 배터리')
 await page.getByRole('dialog').getByRole('button',{name:'선택한 장비 담기'}).click()
 await page.getByRole('button',{name:'카메라B 담기'}).click();await page.getByRole('dialog').getByRole('button',{name:'선택한 장비 담기'}).click()
 await page.getByRole('link',{name:'장바구니',exact:true}).click()
 await expect(page.getByLabel('공용 배터리 장바구니 수량',{exact:true})).toHaveValue('2')
 await page.getByRole('button',{name:'카메라A 삭제',exact:true}).click();await page.getByRole('button',{name:'카메라B 삭제',exact:true}).click()
 await expect(page.getByRole('button',{name:'사용 신청하기'})).toBeDisabled()
 await expect(page.getByRole('alert')).toContainText('연결된 장비와 함께')
})
test('부속품 해제 시 연결 관계를 지우고 일반 목록으로 복귀',async({page})=>{
 await page.addInitScript(()=>{if(!localStorage.getItem('media-equipment'))localStorage.setItem('media-equipment',JSON.stringify([{id:'parent',name:'본체',code:'P',model:'',group:'영상',qty:2,image:'',accessories:[{id:'part',quantity:1,selectedByDefault:true}]},{id:'part',name:'부속품',code:'C',model:'',group:'기타',qty:2,image:'',isAccessory:true}]))})
 await page.goto('http://localhost:5173/admin/equipment/?demo=1');await page.getByRole('button',{name:'부속품 수정',exact:true}).click()
 await page.getByRole('checkbox',{name:'부속품',exact:true}).uncheck()
 await page.locator('.dialog').getByRole('button',{name:'저장',exact:true}).click()
 await page.goto('http://localhost:5173/equipment/?demo=1');await expect(page.getByRole('button',{name:'부속품 담기',exact:true})).toBeVisible()
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('media-equipment')!).find((e:{id:string})=>e.id==='parent').accessories)).toEqual([])
})
