test('승인자 1명·신청자 1명과 미저장 편집의 실시간 미리보기',async({page})=>{
 test.setTimeout(90000)
 await page.goto('http://localhost:5173/admin/pdf/?demo=1')
 await page.evaluate(()=>localStorage.setItem('media-approvers',JSON.stringify([{id:'a',name:'첫승인자',department:'미디어',position:'부장',active:true},{id:'b',name:'제외승인자',department:'사무실',position:'담당',active:true}])))
 await page.reload()
 const region=page.getByRole('region',{name:'신청서 PDF 미리보기'})
 await expect(region.getByRole('status')).toHaveCount(0,{timeout:20000})
 const before=await region.locator('canvas').last().evaluate(c=>(c as HTMLCanvasElement).toDataURL())
 await page.getByLabel('이름',{exact:true}).fill('미저장승인자')
 await expect(region.getByRole('status')).toHaveCount(0,{timeout:20000})
 await expect.poll(async()=>region.locator('canvas').last().evaluate(c=>(c as HTMLCanvasElement).toDataURL()),{timeout:20000}).not.toBe(before)
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'샘플 PDF 저장',exact:true}).click()
 await (await download).saveAs('/tmp/media-signatures.pdf')
 const text=execFileSync('pdftotext',['-layout','/tmp/media-signatures.pdf','-'],{encoding:'utf8'})
 expect(text).toContain('미저장승인자');expect(text).not.toContain('제외승인자');expect(text).toContain('홍길동')
 expect(text).toContain('신청 및 승인');expect(text).toContain('소속');expect(text).toContain('직위');expect(text).toContain('성명')
 const bbox=execFileSync('pdftotext',['-bbox','/tmp/media-signatures.pdf','-'],{encoding:'utf8'})
 const last=bbox.split('<page ').at(-1)!
 const words=Array.from(last.matchAll(/<word xMin="([\d.]+)" yMin="([\d.]+)" xMax="([\d.]+)" yMax="([\d.]+)">(.*?)<\/word>/g))
 const heading=words.find(w=>w[5]==='신청')!
 const noticeEnd=Math.max(...words.filter(w=>Number(w[2])<Number(heading[2])&&Number(w[2])>350).map(w=>Number(w[4])))
 expect(Number(heading[2])-noticeEnd).toBeLessThan(30)
 await page.getByRole('button',{name:'승인자 저장',exact:true}).click()
 await page.reload()
 await expect(page.getByLabel('이름',{exact:true})).toHaveValue('미저장승인자')
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('media-approvers')!).length)).toBe(1)
})
