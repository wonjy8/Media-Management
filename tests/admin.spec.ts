import { test,expect } from '@playwright/test'
test.use({launchOptions:{executablePath:'/usr/bin/chromium',args:['--no-sandbox']}})
test('관리자 그룹·장비 등록, 수정, 비활성화',async({page})=>{
 await page.goto('http://localhost:5173/admin/equipment/?demo=1')
 await page.getByRole('link',{name:'그룹 관리',exact:true}).click()
 await page.getByLabel('그룹명',{exact:true}).fill('교육 장비')
 await page.getByRole('button',{name:'그룹 추가',exact:true}).click()
 await expect(page.getByText('교육 장비',{exact:true})).toBeVisible()
 await page.getByRole('link',{name:'장비 관리',exact:true}).click()
 await page.getByRole('button',{name:'장비 등록',exact:true}).click()
 const dialog=page.locator('.dialog')
 await dialog.getByLabel('장비명',{exact:true}).fill('테스트 프로젝터')
 await dialog.getByLabel('관리번호',{exact:true}).fill('VID-TEST')
 await dialog.getByLabel('모델명',{exact:true}).fill('EPSON')
 await dialog.getByLabel('그룹',{exact:true}).selectOption({label:'교육 장비'})
 await dialog.getByLabel('총 수량',{exact:true}).fill('3')
 await dialog.getByLabel('수리 필요 수량',{exact:true}).fill('1')
 await dialog.getByLabel('설명 · 구성품 · 주의사항',{exact:true}).fill('리모컨, 전원 케이블')
 await dialog.getByRole('button',{name:'저장',exact:true}).click()
 await expect(page.getByText('테스트 프로젝터',{exact:true})).toBeVisible()
 await page.goto('http://localhost:5173/?demo=1')
 await page.getByPlaceholder('장비명, 모델명 검색').fill('테스트 프로젝터')
 await expect(page.locator('.card')).toHaveCount(1)
 await expect(page.locator('.card-bottom')).toContainText('2')
 await page.goto('http://localhost:5173/admin/equipment/?demo=1')
 await page.getByRole('button',{name:'테스트 프로젝터 수정',exact:true}).click()
 await page.getByLabel('대여 목록에 표시',{exact:true}).uncheck()
 await page.locator('.dialog').getByRole('button',{name:'저장',exact:true}).click()
 await page.goto('http://localhost:5173/?demo=1')
 await page.getByPlaceholder('장비명, 모델명 검색').fill('테스트 프로젝터')
 await expect(page.locator('.card')).toHaveCount(0)
})
test('이미지 업로드는 1MB 이하 JPG로 압축',async({page})=>{
 await page.goto('http://localhost:5173/admin/equipment/?demo=1')
 const png=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=1900;c.height=1900;const ctx=c.getContext('2d')!;const data=ctx.createImageData(1900,1900);for(let i=0;i<data.data.length;i+=4){data.data[i]=Math.random()*255;data.data[i+1]=Math.random()*255;data.data[i+2]=Math.random()*255;data.data[i+3]=255}ctx.putImageData(data,0,0);return c.toDataURL('image/png').split(',')[1]})
 await page.getByRole('button',{name:'장비 등록',exact:true}).click()
 await page.getByLabel('장비명',{exact:true}).fill('사진 테스트')
 await page.getByLabel('관리번호',{exact:true}).fill('IMG-001')
 await page.getByLabel('장비 이미지',{exact:true}).setInputFiles({name:'noise.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')})
 await page.locator('.dialog').getByRole('button',{name:'저장',exact:true}).click()
 await expect(page.locator('.dialog')).toHaveCount(0,{timeout:15000})
 const image=await page.evaluate(()=>JSON.parse(localStorage.getItem('media-equipment')!).find((e:{name:string})=>e.name==='사진 테스트').image)
 expect(image.startsWith('data:image/jpeg;base64,')).toBe(true)
 expect(Buffer.from(image.split(',')[1],'base64').length).toBeLessThanOrEqual(1_000_000)
})
