import { test, expect } from '@playwright/test'
test.use({ launchOptions: { executablePath: '/usr/bin/chromium', args:['--no-sandbox'] } })
test('신청, 반출, 부분 반납', async ({page})=>{
 await page.goto('http://localhost:5173/?demo=1')
 await page.getByRole('button',{name:'무선 핸드 마이크 담기'}).click()
 await page.getByRole('button',{name:'무선 핸드 마이크 담기'}).click()
 await page.getByRole('button',{name:'반출 신청하기'}).click()
 const dialog=page.locator('.dialog')
 await dialog.getByLabel('이름',{exact:true}).fill('테스트')
 await dialog.getByLabel('전화번호').fill('01000000000')
 await dialog.getByLabel('반출일',{exact:true}).fill('2026-11-01')
 await dialog.getByLabel('반납 예정일').fill('2026-11-03')
 await dialog.getByLabel('대여 사유').fill('테스트 예배')
 await dialog.getByRole('button',{name:'신청 완료',exact:true}).click()
 await expect(page.getByText('신청이 완료되었어요')).toBeVisible()
 await page.getByRole('button',{name:'닫기',exact:true}).click()
 await page.getByRole('button',{name:'관리자',exact:false}).click()
 await page.getByRole('button',{name:'반출 · 반납',exact:true}).click()
 await page.getByRole('button',{name:'승인',exact:true}).click()
 await page.getByRole('button',{name:'실제 반출 확인'}).click()
 await page.getByRole('button',{name:'신청 조회 · 반납'}).click()
 await page.getByLabel('이름',{exact:true}).fill('테스트')
 await page.getByLabel('전화번호').fill('01000000000')
 await page.getByRole('button',{name:'조회하기'}).click()
 await expect(page.getByText('미반납 2개')).toBeVisible()
 await page.locator('.return-row input[type=checkbox]').check()
 await page.getByLabel('반납 수량').fill('1')
 await page.getByRole('button',{name:'선택한 장비 반납',exact:true}).click()
 await page.getByRole('button',{name:'반납 완료',exact:true}).click()
 await expect(page.getByText('미반납 1개')).toBeVisible()
})
test('모바일 검색 및 가로 넘침',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('http://localhost:5173/?demo=1')
 await page.getByPlaceholder('장비명, 모델명 검색').fill('SONY')
 await expect(page.locator('.card')).toHaveCount(1)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:'/tmp/media-mobile.png',fullPage:true})
})
