test('전화번호 검증, 반려 사유 노출, 수정 재신청과 상태 테두리',async({page})=>{
 await page.goto('http://localhost:5173/?demo=1')
 await page.getByRole('button',{name:'무선 핸드 마이크 담기'}).click()
 await page.getByRole('link',{name:'장바구니',exact:true}).click()
 await page.getByRole('button',{name:'사용 신청하기'}).click()
 await page.getByLabel('이름',{exact:true}).fill('반려 테스트')
 await page.getByLabel('소속',{exact:true}).fill('청년부')
 await page.getByLabel('직위',{exact:true}).fill('팀원')
 await page.getByLabel('대여 사유').fill('예배')
 for(const phone of ['010-1234-5678','01112345678','0101234567','abcdefghijk']){
  await page.getByLabel('전화번호',{exact:true}).fill(phone)
  await expect(page.getByRole('button',{name:'신청 완료',exact:true})).toBeDisabled()
 }
 await page.getByLabel('전화번호',{exact:true}).fill('01012345678')
 await expect(page.getByLabel('특이사항',{exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'신청 완료',exact:true}).click()
 await expect(page.getByRole('region',{name:'신청서 PDF 미리보기'}).getByRole('img')).toHaveCount(1,{timeout:20000})
 const popup=page.waitForEvent('popup');await page.getByRole('link',{name:'관리자',exact:false}).click();const admin=await popup
 await admin.getByRole('link',{name:'반출 · 반납',exact:true}).click()
 await expect(admin.getByRole('button',{name:'반납 사진',exact:true})).toHaveCount(0)
 await admin.getByRole('button',{name:'반려',exact:true}).click()
 await expect(admin.getByRole('button',{name:'반려하기',exact:true})).toBeDisabled()
 await admin.getByLabel('반려 사유',{exact:true}).fill('행사 일정이 변경되었습니다.')
 await admin.getByRole('button',{name:'반려하기',exact:true}).click()
 await expect(admin.locator('.loan-rejected')).toContainText('행사 일정이 변경되었습니다.')
 await page.getByRole('link',{name:'신청 조회 · 반납'}).click()
 await page.getByRole('button',{name:'조회하기'}).click()
 await expect(page.locator('.loan-rejected')).toContainText('반려 사유: 행사 일정이 변경되었습니다.')
 await expect(page.locator('.loan-rejected')).toHaveCSS('border-top-color','rgb(204, 61, 61)')
 await page.getByRole('button',{name:'수정',exact:true}).click()
 await page.getByLabel('소속',{exact:true}).fill('청년부')
 await page.getByLabel('직위',{exact:true}).fill('팀원')
 await page.getByLabel('대여 사유').fill('변경된 예배')
 await page.getByRole('button',{name:'수정 저장'}).click()
 await page.getByRole('link',{name:'신청 조회 · 반납'}).click()
 await page.getByRole('button',{name:'조회하기'}).click()
 await expect(page.locator('.loan-pending')).toHaveCSS('border-top-color','rgb(214, 169, 0)')
 await admin.reload()
 await admin.getByRole('button',{name:'승인',exact:true}).click()
 await expect(admin.locator('.loan-approved')).toBeVisible()
 await page.reload();await page.getByLabel('이름',{exact:true}).fill('반려 테스트');await page.getByLabel('전화번호').fill('01012345678');await page.getByRole('button',{name:'조회하기'}).click()
 await expect(page.locator('.loan-approved')).toHaveCSS('border-top-color','rgb(38, 131, 75)')
 await page.locator('.return-row input[type=checkbox]').check()
 await page.getByRole('button',{name:'선택한 장비 반납'}).click()
 await expect(page.locator('input[type=file]')).toHaveCount(0)
 await page.getByRole('button',{name:'반납 완료',exact:true}).click()
 await expect(page.locator('.loan-returned')).toHaveCSS('border-top-color','rgb(32, 32, 32)')
 await admin.close()
})
