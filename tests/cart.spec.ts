test('필수 입력은 선택한 칸만 안내하고 소속·직위까지 입력해야 신청 가능',async({page})=>{
 await page.goto('http://localhost:5173/?demo=1')
 await page.getByRole('button',{name:'무선 핸드 마이크 담기'}).click()
 await page.getByRole('link',{name:'장바구니',exact:true}).click()
 await page.getByRole('button',{name:'사용 신청하기'}).click()
 await expect(page.locator('.input-error')).toHaveCount(0)
 const phone=page.getByLabel('전화번호',{exact:true})
 const phoneField=phone.locator('..')
 await expect(phoneField.locator('.input-help')).toHaveText('전화번호는 - 없이 01000000000 형식으로 입력해 주세요.')
 const inputBox=(await phone.boundingBox())!,helpBox=(await phoneField.locator('.input-help').boundingBox())!
 expect(helpBox.y).toBeGreaterThanOrEqual(inputBox.y+inputBox.height)
 expect(helpBox.y-inputBox.y-inputBox.height).toBeLessThan(12)
 await page.getByLabel('소속',{exact:true}).click()
 await expect(page.locator('.input-error')).toHaveCount(1)
 await expect(page.getByLabel('소속',{exact:true})).toHaveAttribute('aria-invalid','true')
 await expect(page.locator('.input-error')).toHaveCSS('color','rgb(200, 49, 49)')
 await page.getByLabel('소속',{exact:true}).fill('청년부')
 await expect(page.locator('.input-error')).toHaveCount(0)
 await page.getByLabel('소속',{exact:true}).fill('  ')
 await expect(page.locator('.input-error')).toHaveCount(1)
 await page.getByLabel('소속',{exact:true}).fill('청년부')
 await page.getByLabel('이름',{exact:true}).fill('테스트')
 await phone.fill('01012345678')
 await page.getByLabel('대여 사유').fill('예배')
 await expect(page.getByRole('button',{name:'신청 완료',exact:true})).toBeDisabled()
 await page.getByLabel('직위',{exact:true}).click()
 await expect(page.getByLabel('직위',{exact:true})).toHaveAttribute('aria-invalid','true')
 await page.getByLabel('직위',{exact:true}).fill('팀장')
 await expect(page.locator('.input-error')).toHaveCount(0)
 await expect(page.getByRole('button',{name:'신청 완료',exact:true})).toBeEnabled()
 await page.getByRole('button',{name:'신청 완료',exact:true}).click()
 await expect(page.getByRole('heading',{name:'신청이 완료되었어요'})).toBeVisible()
 const loan=await page.evaluate(()=>JSON.parse(localStorage.getItem('media-loans')!)[0])
 expect(loan.department).toBe('청년부');expect(loan.position).toBe('팀장')
})
