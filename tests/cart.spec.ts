import {test,expect} from '@playwright/test'
test.use({launchOptions:{executablePath:'/usr/bin/chromium',args:['--no-sandbox']}})
test('장바구니 수량·삭제·새로고침, 날짜는 신청 화면에서만 입력',async({page})=>{
 await page.goto('http://localhost:5173/equipment/?demo=1')
 await expect(page.getByLabel('반출일',{exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'무선 핸드 마이크 담기',exact:true}).click()
 await page.getByRole('button',{name:'무선 핸드 마이크 담기',exact:true}).click()
 await page.getByRole('button',{name:'XLR 케이블 5m 담기',exact:true}).click()
 await page.getByRole('link',{name:'장바구니',exact:true}).click()
 await expect(page).toHaveURL(/\/cart\//)
 await expect(page.locator('.cart-item')).toHaveCount(2)
 await page.getByLabel('무선 핸드 마이크 장바구니 수량',{exact:true}).fill('3')
 await page.getByRole('button',{name:'XLR 케이블 5m 삭제',exact:true}).click()
 await page.reload()
 await expect(page.locator('.cart-item')).toHaveCount(1)
 await expect(page.getByLabel('무선 핸드 마이크 장바구니 수량',{exact:true})).toHaveValue('3')
 await page.getByRole('button',{name:'대여하기',exact:true}).click()
 await expect(page).toHaveURL(/\/checkout\//)
 await expect(page.locator('.overlay')).toHaveCount(0)
 await expect(page.getByLabel('이름',{exact:true})).toBeVisible()
 await expect(page.getByLabel('반출일',{exact:true})).toBeVisible()
 await page.getByLabel('이름',{exact:true}).fill('테스트')
 await page.getByLabel('전화번호').fill('01000000000')
 await page.getByLabel('대여 사유').fill('장바구니 테스트')
 await page.getByLabel('반출일',{exact:true}).fill('2027-01-02')
 await page.getByLabel('반납 예정일',{exact:true}).fill('2027-01-04')
 await page.getByRole('button',{name:'신청 완료',exact:true}).click()
 await expect(page.getByRole('heading',{name:'신청이 완료되었어요'})).toBeVisible()
 await expect(page.locator('.overlay')).toHaveCount(0)
 const stored=await page.evaluate(()=>({loans:JSON.parse(localStorage.getItem('media-loans')!),cart:JSON.parse(localStorage.getItem('media-cart-demo')!)}))
 expect(stored.cart).toEqual({})
 expect(stored.loans[0].items['AUD-001']).toBe(3)
 expect(stored.loans[0].start).toBe('2027-01-02')
 expect(stored.loans[0].end).toBe('2027-01-04')
})
test('장바구니 자체는 날짜와 무관하며 신청 기간의 중복만 차단',async({page})=>{
 await page.addInitScript(()=>{localStorage.setItem('media-loans',JSON.stringify([{id:'반출-2027-01-001',name:'다른이',phone:'01000000001',reason:'예약',start:'2027-01-01',end:'2027-01-05',note:'',items:{'AUD-001':4},returned:{},approved:false,out:false}]))})
 await page.goto('http://localhost:5173/equipment/?demo=1')
 await page.getByRole('button',{name:'무선 핸드 마이크 담기',exact:true}).click()
 await page.getByRole('link',{name:'장바구니',exact:true}).click()
 await page.getByRole('button',{name:'대여하기',exact:true}).click()
 await page.getByLabel('이름',{exact:true}).fill('테스트')
 await page.getByLabel('전화번호').fill('01000000000')
 await page.getByLabel('대여 사유').fill('예약 테스트')
 await page.getByLabel('반출일',{exact:true}).fill('2027-01-02')
 await page.getByLabel('반납 예정일',{exact:true}).fill('2027-01-04')
 await page.getByRole('button',{name:'신청 완료',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('대여 가능 수량이 변경')
 await expect(page.getByLabel('이름',{exact:true})).toHaveValue('테스트')
 await page.getByLabel('반출일',{exact:true}).fill('2027-01-06')
 await page.getByLabel('반납 예정일',{exact:true}).fill('2027-01-08')
 await page.getByRole('button',{name:'신청 완료',exact:true}).click()
 await expect(page.getByRole('heading',{name:'신청이 완료되었어요'})).toBeVisible()
})
